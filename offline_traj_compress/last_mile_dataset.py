def find_hdf5_path(task_description, root_dir):
    """
    通过文件名匹配查找 HDF5 文件。
    Libero 的文件名通常包含任务描述（空格替换为下划线）。
    """
    if not hasattr(find_hdf5_path, "cache"): find_hdf5_path.cache = {}
    if task_description in find_hdf5_path.cache: return find_hdf5_path.cache[task_description]

    # 将任务描述中的空格转换为下划线，Libero文件名通常是全小写的
    target_pattern = task_description.replace(" ", "_").lower()
    
    print(f"Searching file containing pattern: '{target_pattern}' in {root_dir}...")

    for root, _, files in os.walk(root_dir):
        for file in files:
            if file.endswith(".hdf5"):
                # 放宽匹配条件，只要包含 pattern 即可
                if target_pattern in file.lower():
                    path = os.path.join(root, file)
                    print(f"  Found match: {file}")
                    find_hdf5_path.cache[task_description] = path
                    return path
    
    return None

def get_env_args(h5_file):
    """
    从 HDF5 文件中安全提取 env_args
    """
    env_args = None
    # 1. 尝试从 data 组的属性获取
    if "data" in h5_file and "env_args" in h5_file["data"].attrs:
        env_args = h5_file["data"].attrs["env_args"]
    # 2. 尝试从文件根属性获取
    elif "env_args" in h5_file.attrs:
        env_args = h5_file.attrs["env_args"]
    
    if env_args is None:
        raise ValueError("Could not find 'env_args' in HDF5 attributes.")
    
    # 如果是字符串形式的 JSON，则解析它
    if isinstance(env_args, str):
        env_args = json.loads(env_args)
    
    return env_args

def run_replay():
    # 按照 Task 分组处理，避免重复加载环境
    tasks = {}
    for item in last_mile_slice:
        tasks.setdefault(item['original_task'], []).append(item)

    for task_desc, items in tasks.items():
        # 1. 找到对应的 HDF5 文件
        hdf5_path = find_hdf5_path(task_desc, DATASET_ROOT)
        if not hdf5_path:
            print(f"[Error] Could not find HDF5 file for task: {task_desc}")
            continue
            
        print(f"\n========== Processing Task: {task_desc} ==========")
        print(f"File: {os.path.basename(hdf5_path)}")

        # 2. 加载环境 (只加载一次)
        with h5py.File(hdf5_path, 'r') as f:
            try:
                env_args = get_env_args(f)
            except Exception as e:
                print(f"[Error] Failed to load env_args: {e}")
                continue

            # === 关键修正 1: 强制覆盖渲染参数，确保 OffScreenRenderEnv 工作 ===
            # Robosuite/Libero 使用 has_offscreen_renderer 而不是 render_mode
            env_args["has_renderer"] = False
            env_args["has_offscreen_renderer"] = True
            env_args["use_camera_obs"] = True
            env_args["camera_names"] = ["agentview"] 
            env_args["camera_heights"] = 256
            env_args["camera_widths"] = 256
            
            # === 关键修正 2: 修复 BDDL 文件路径 ===
            # HDF5 中记录的 bddl_file_name 可能是别人电脑上的绝对路径，需要提取文件名
            if "bddl_file_name" in env_args:
                bddl_full_path = env_args["bddl_file_name"]
                # 假设 BDDL 文件在 Libero 默认路径下，或者我们只需要文件名
                # 这里只保留文件名，Libero 环境通常能自动在 assets 中找到它
                env_args["bddl_file_name"] = os.path.basename(bddl_full_path)

            try:
                # 创建环境
                print("Creating environment...")
                env = OffScreenRenderEnv(**env_args)
            except Exception as e:
                print(f"[Error] Failed to create environment: {e}")
                print("Tip: check if 'libero' is correctly installed and assets are available.")
                continue
            
            # 检查环境状态维度，避免 set_state 报错
            current_sim_state_dim = env.sim.get_state().flatten().shape[0]
            
            for item in items:
                ep_idx = item['episode_index']
                demo_key = f"demo_{ep_idx}"
                
                if "data" not in f or demo_key not in f["data"]:
                    print(f"  [Skip] Episode {ep_idx} not found in file.")
                    continue

                # 3. 提取数据
                demo_grp = f["data"][demo_key]
                states = demo_grp["states"][()]   # MuJoCo Physics States
                actions = demo_grp["actions"][()] # Robot Actions
                
                start_f = item['frame_start']
                end_f = item['frame_end']
                
                # 边界检查
                if start_f >= len(states) or end_f > len(actions):
                    print(f"  [Error] ID {item['id']}: Indices out of bounds (Len states: {len(states)}, Start: {start_f}).")
                    continue

                # 4. 重置环境并设置状态
                env.reset()
                
                # === 关键修正 3: 安全设置状态 ===
                saved_state_dim = states[start_f].shape[0]
                
                # 如果维度不匹配，尝试从头回放 (虽然慢，但是稳)
                if saved_state_dim != current_sim_state_dim:
                    print(f"  [Warning] State dimension mismatch (Saved: {saved_state_dim}, Env: {current_sim_state_dim}). Replaying from start...")
                    # 必须从第0帧开始 step 到 start_f
                    # 设置初始状态 (第0帧)
                    # 注意：有些数据集 states[0] 可能也不是完整物理状态，如果报错则只能 env.reset() 后 step
                    try:
                        env.sim.set_state_from_flattened(states[0])
                        env.sim.forward()
                    except:
                        env.reset() # Fallback
                    
                    # 空跑以达到起始帧
                    for _ in range(start_f):
                        # 如果需要非常精确，应该用 actions[_]，但这里没有从0开始的actions列表的引用
                        # 简单处理：如果必须从头跑，且没有完整 action 列表，这里的 Last Mile Replay 可能会失败
                        # 由于你只想渲染片段，我们假设 states[start_f] 是可用的。
                        # 如果 Libero 数据集标准，states 就是 xml state，如果不匹配，可能是 env 版本问题
                        pass
                    
                    print(f"  [Skip] Skipping ID {item['id']} due to state dimension mismatch. Cannot teleport.")
                    continue
                else:
                    # 维度匹配，直接瞬移
                    env.sim.set_state_from_flattened(states[start_f])
                    env.sim.forward()

                frames = []
                success_flag = False
                
                print(f"  > Replaying ID {item['id']} ({item['action_type']}): Ep {ep_idx}, Frame {start_f}->{end_f}")

                # 5. 执行 Replay
                for i in range(start_f, end_f):
                    action = actions[i]
                    
                    # 渲染与执行
                    obs, _, _, info = env.step(action)
                    
                    # 获取图像
                    # 这里的 key 取决于 camera_names 设置
                    if "agentview_image" in obs:
                        img = obs["agentview_image"]
                        # Robosuite 渲染出来通常是倒置的，需要翻转
                        frames.append(img[::-1]) 
                    else:
                        print(f"    [Warning] 'agentview_image' not in obs. Keys: {list(obs.keys())}")
                        break
                    
